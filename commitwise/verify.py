    """Demo helper: injects a fabricated hallucinated claim to demonstrate the honesty verifier."""
    cloned = dict(analysis_data)
    cloned_impact = list(cloned.get("impact_summary", []))

    # Injects an intentionally fabricated claim with:
    # 1. An unknown evidence ID (E99)
    # 2. A phantom file (auth/legacy_bypass.py)
    # 3. A phantom function (disable_all_security())
