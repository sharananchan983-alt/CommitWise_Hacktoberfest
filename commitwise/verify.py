"""Honesty Verification Engine for CommitWise.

Performs deterministic, non-AI verification of all claims generated by the LLM:
1. Missing citation check: Did a claim fail to cite evidence?
2. Unknown citation check: Does a cited evidence ID exist in the catalog?
3. Phantom file check: Does a claim mention a file not in the evidence?
4. Phantom symbol check: Does a claim mention a function/class not in the evidence?
5. Relevance check: Does the cited evidence support the category of claim?
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional, Set

from .evidence import EvidenceReport


@dataclass
class VerifiedClaim:
    """A claim that passed honesty checks."""
    category: str
    claim_text: str
    evidence_ids: List[str]
    supporting_evidence: List[str]
    metadata: Dict[str, Any] = field(default_factory=dict)


@dataclass
class FlaggedClaim:
    """A claim that failed one or more honesty checks."""
    category: str
    claim_text: str
    evidence_ids: List[str]
    violations: List[str]
    metadata: Dict[str, Any] = field(default_factory=dict)


@dataclass
class VerificationReport:
    """Overall report produced by the non-AI honesty engine."""
    passed: bool
    total_claims: int
    verified_count: int
    flagged_count: int
    honesty_score: float  # 0.0 to 100.0%
    verified_claims: List[VerifiedClaim] = field(default_factory=list)
    flagged_claims: List[FlaggedClaim] = field(default_factory=list)
    summary: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return {
            "passed": self.passed,
            "total_claims": self.total_claims,
            "verified_count": self.verified_count,
            "flagged_count": self.flagged_count,
            "honesty_score": self.honesty_score,
            "summary": self.summary,
            "flagged_claims": [
                {
                    "category": f.category,
                    "claim_text": f.claim_text,
                    "evidence_ids": f.evidence_ids,
                    "violations": f.violations,
                }
                for f in self.flagged_claims
            ],
            "verified_claims": [
                {
                    "category": v.category,
                    "claim_text": v.claim_text,
                    "evidence_ids": v.evidence_ids,
                }
                for v in self.verified_claims
            ],
        }


def extract_potential_filenames(text: str) -> Set[str]:
    """Find potential file paths mentioned in a string (e.g. auth/token.py or docs/auth.md)."""
    # Matches words with file extensions or slashes like dir/file.ext
    pattern = r"\b[a-zA-Z0-9_\-./]+\.[a-zA-Z0-9]{1,5}\b"
    candidates = re.findall(pattern, text)
    valid_extensions = {
        ".py", ".js", ".ts", ".jsx", ".tsx", ".md", ".rst", ".txt",
        ".json", ".yaml", ".yml", ".html", ".css", ".sh", ".toml"
    }
    found = set()
    for c in candidates:
        cleaned = c.strip("`'\",:;()[]{}")
        # Check if it has a recognized code/doc extension
        for ext in valid_extensions:
            if cleaned.endswith(ext):
                found.add(cleaned.replace("\\", "/"))
                break
    return found


def extract_potential_symbols(text: str) -> Set[str]:
    """Find potential function or method calls mentioned in a string (e.g., func_name() or func_name)."""
    # Matches identifier followed by ()
    calls = re.findall(r"\b([a-zA-Z_][a-zA-Z0-9_]*)\(\)", text)
    # Matches `identifier`
    backticks = re.findall(r"`([a-zA-Z_][a-zA-Z0-9_]*)`", text)

    # Common English words or keywords to ignore
    ignore = {
        "true", "false", "none", "null", "if", "for", "while", "return", "import",
        "def", "class", "git", "diff", "head", "ast", "api", "ui", "jwt", "id", "url"
    }

    found = set()
    for s in calls + backticks:
        s_lower = s.lower()
        if s_lower not in ignore and len(s) > 2:
            found.add(s)

    return found


def verify_claims(
    analysis_data: Dict[str, Any],
    evidence: EvidenceReport,
) -> VerificationReport:
    """Check every claim in the AI analysis against the ground-truth evidence."""
    verified_claims: List[VerifiedClaim] = []
    flagged_claims: List[FlaggedClaim] = []

    valid_ids: Set[str] = evidence.all_ids()
    valid_files: Set[str] = evidence.all_changed_files()
    # Also add files found in doc matches or caller lists
    for doc in evidence.doc_matches:
        if "doc_file" in doc:
            valid_files.add(doc["doc_file"])
    for call_list in evidence.callers.values():
        for c in call_list:
            valid_files.add(c.split(":")[0])

    valid_symbols: Set[str] = evidence.all_symbols()

    # 1. Verify Impact Summary items
    for item in analysis_data.get("impact_summary", []):
        claim_text = item.get("claim", "")
        cited_ids = item.get("evidence_ids", [])
        violations: List[str] = []

        # Check A: Missing Citation
        if not cited_ids:
            violations.append("MISSING_CITATION: Claim does not cite any evidence ID.")

        # Check B: Unknown Citation
        for eid in cited_ids:
            if eid not in valid_ids:
                violations.append(f"UNKNOWN_EVIDENCE_ID: Cited ID '{eid}' does not exist in the evidence catalog.")

        # Check C: Phantom Files
        mentioned_files = extract_potential_filenames(claim_text)
        for f in mentioned_files:
            # Check if basename or relative path exists in valid files
            if f not in valid_files and not any(vf.endswith(f) or f.endswith(vf) for vf in valid_files):
                violations.append(f"PHANTOM_FILE: Mentions file '{f}' which is not in the changed files or evidence.")

        # Check D: Phantom Symbols
        mentioned_symbols = extract_potential_symbols(claim_text)
        for sym in mentioned_symbols:
            if sym not in valid_symbols:
                violations.append(f"PHANTOM_SYMBOL: Mentions function/symbol '{sym}()' which was never touched or found in evidence.")

        # Determine outcome
        if violations:
            flagged_claims.append(FlaggedClaim(
                category="impact_claim",
                claim_text=claim_text,
                evidence_ids=cited_ids,
                violations=violations,
                metadata=item,
            ))
        else:
            supporting = [
                evidence.get_item(eid).summary
                for eid in cited_ids
                if evidence.get_item(eid) is not None
            ]
            verified_claims.append(VerifiedClaim(
                category="impact_claim",
                claim_text=claim_text,
                evidence_ids=cited_ids,
                supporting_evidence=supporting,
                metadata=item,
            ))

    # 2. Verify Doc Updates
    for doc_item in analysis_data.get("doc_updates", []):
        doc_file = doc_item.get("doc_file", "")
        suggestion = doc_item.get("suggested_change", "")
        cited_ids = doc_item.get("evidence_ids", [])
        violations = []

        if not cited_ids:
            violations.append("MISSING_CITATION: Doc update suggestion does not cite any evidence ID.")

        for eid in cited_ids:
            if eid not in valid_ids:
                violations.append(f"UNKNOWN_EVIDENCE_ID: Cited ID '{eid}' does not exist in evidence catalog.")

        # Check if doc_file exists or was referenced
        if doc_file:
            cleaned_doc = doc_file.strip("`'\"")
            if cleaned_doc not in valid_files and not any(vf.endswith(cleaned_doc) for vf in valid_files):
                violations.append(f"PHANTOM_FILE: Suggested updating '{doc_file}' which is not in evidence or repo docs.")

        if violations:
            flagged_claims.append(FlaggedClaim(
                category="doc_update",
                claim_text=f"Update {doc_file}: {suggestion}",
                evidence_ids=cited_ids,
                violations=violations,
                metadata=doc_item,
            ))
        else:
            supporting = [
                evidence.get_item(eid).summary
                for eid in cited_ids
                if evidence.get_item(eid) is not None
            ]
            verified_claims.append(VerifiedClaim(
                category="doc_update",
                claim_text=f"Update {doc_file}: {suggestion}",
                evidence_ids=cited_ids,
                supporting_evidence=supporting,
                metadata=doc_item,
            ))

    # 3. Verify Suggested Reviewers
    for rev_item in analysis_data.get("suggested_reviewers", []):
        name = rev_item.get("name", "")
        reason = rev_item.get("reason", "")
        cited_ids = rev_item.get("evidence_ids", [])
        violations = []

        if not cited_ids:
            violations.append("MISSING_CITATION: Reviewer suggestion does not cite any evidence ID.")

        for eid in cited_ids:
            if eid not in valid_ids:
                violations.append(f"UNKNOWN_EVIDENCE_ID: Cited ID '{eid}' does not exist in evidence catalog.")

        # Check if the cited evidence actually refers to blame
        for eid in cited_ids:
            item = evidence.get_item(eid)
            if item and item.category != "blame":
                violations.append(f"EVIDENCE_MISMATCH: Cited '{eid}' is category '{item.category}', not 'blame'.")

        if violations:
            flagged_claims.append(FlaggedClaim(
                category="reviewer",
                claim_text=f"Reviewer {name}: {reason}",
                evidence_ids=cited_ids,
                violations=violations,
                metadata=rev_item,
            ))
        else:
            supporting = [
                evidence.get_item(eid).summary
                for eid in cited_ids
                if evidence.get_item(eid) is not None
            ]
            verified_claims.append(VerifiedClaim(
                category="reviewer",
                claim_text=f"Reviewer {name}: {reason}",
                evidence_ids=cited_ids,
                supporting_evidence=supporting,
                metadata=rev_item,
            ))

    total_claims = len(verified_claims) + len(flagged_claims)
    honesty_score = (
        round((len(verified_claims) / total_claims) * 100, 1) if total_claims > 0 else 100.0
    )
    passed = len(flagged_claims) == 0

    if passed:
        summary = f"All {total_claims} claims verified against git and AST evidence (100% honesty score)."
    else:
        summary = (
            f"Flagged {len(flagged_claims)} out of {total_claims} claims. "
            f"Honesty score: {honesty_score}%."
        )

    return VerificationReport(
        passed=passed,
        total_claims=total_claims,
        verified_count=len(verified_claims),
        flagged_count=len(flagged_claims),
        honesty_score=honesty_score,
        verified_claims=verified_claims,
        flagged_claims=flagged_claims,
        summary=summary,
    )


